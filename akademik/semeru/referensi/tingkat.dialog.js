$( document ).ready(function()
{
    $("#tingkat").focus();

    document.addEventListener('keydown', function(event) 
    {
        if (event.key === 'Escape') 
            window.close(); 
    });
});

function simpanTingkat()
{
    const isValid = Vldr.InputText("tingkat", "Tingkat", 1, 50) &&
                    Vldr.IsInteger("urutan", "Urutan") &&
                    Vldr.IsNotNegative("urutan", "Urutan") &&
                    Vldr.IsNotZero("urutan", "Urutan") &&
                    Vldr.IsNotEmpty("departemen", "Departemen");

    if (!isValid)
        return;

    let qsb = new QsBuilder();
    qsb.add("op", "save");
    qsb.addInput("replid", "replid");
    qsb.addInput("departemen", "departemen");
    qsb.addInput("tingkat", "tingkat");
    qsb.addInput("urutan", "urutan");
    qsb.addInput("keterangan", "keterangan");

    let btnSimpan = $("#btnSimpan");
    let btnTutup = $("#btnTutup");

    btnSimpan.prop("disabled", true);
    btnTutup.prop("disabled", true);

    $.ajax({
        url: "tingkat.dialog.ajax.php",
        method: "POST",
        data: qsb.createQs(),
        success: function (json)
        {
            let response = JSON.parse(json);
            if (parseInt(response[0]) < 0)
            {
                btnSimpan.prop("disabled", false);
                btnTutup.prop("disabled", false);

                alert(response[1]);
                return;
            }

            opener.refresh();
            window.close();
        },
        error: function (xhr)
        {
            btnSimpan.prop("disabled", false);
            btnTutup.prop("disabled", false);

            alert(xhr.responseText);
        }
    });
}